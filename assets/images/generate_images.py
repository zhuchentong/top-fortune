#!/usr/bin/env python3
"""Generate the top-fortune tube artwork as an LVGL9 RGB565A8 C array.

Draws the divination-stick tube at 4x with Pillow (rounded shapes, vertical
bamboo gradient, gold band, one cinnabar-tipped stick), downscales with
Lanczos for anti-aliased edges, and emits:

    assets/images/fortune_img.c   -> const lv_image_dsc_t fortune_img_tube

RGB565A8 layout (LVGL9): w*h*2 bytes little-endian RGB565, then w*h bytes
alpha. stride = w*2 (color plane only). Regenerate after editing this script:

    python3 assets/images/generate_images.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "assets" / "images" / "fortune_img.c"

S = 4                       # supersample factor
FINAL_W, FINAL_H = 120, 132
W, H = FINAL_W * S, FINAL_H * S

WOOD_HI = (154, 106, 56)    # 0x9A6A38 bamboo lit side
WOOD = (122, 78, 35)        # 0x7A4E23 bamboo mid
WOOD_LO = (92, 58, 26)      # 0x5C3A1A bamboo shade
OPENING = (44, 27, 12)
STICK = (216, 192, 138)     # 0xD8C08A bamboo stick
STICK_LO = (176, 150, 96)
CINNABAR = (176, 58, 46)    # 0xB03A2E lucky stick tip
GOLD = (196, 148, 44)
INK = (59, 47, 47)          # 0x3B2F2F shadow tone


def lerp(a, b, t: float) -> tuple:
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def draw_artwork() -> Image.Image:
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))

    # 接地软阴影（先画，垫底）。
    shadow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).ellipse([96, 482, 384, 518], fill=INK + (70,))
    shadow = shadow.filter(ImageFilter.GaussianBlur(7))
    img = Image.alpha_composite(img, shadow)

    draw = ImageDraw.Draw(img)

    # 竹签：5 支露头，第 3 支朱砂签头。
    stick_x = [112, 176, 240, 304, 352]
    stick_top = [48, 20, 60, 28, 72]
    for i, (x, t) in enumerate(zip(stick_x, stick_top)):
        draw.rounded_rectangle([x, t, x + 24, 200], radius=8,
                               fill=STICK + (255,))
        draw.rectangle([x + 17, t + 8, x + 22, 194], fill=STICK_LO + (255,))
        if i == 2:
            draw.rounded_rectangle([x, t, x + 24, t + 30], radius=8,
                                   fill=CINNABAR + (255,))

    # 筒身：垂直竹色渐变，圆角矩形蒙版。
    top_y, bot_y = 208, 478
    grad = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    gdraw = ImageDraw.Draw(grad)
    for y in range(top_y, bot_y):
        color = lerp(WOOD_HI, WOOD_LO, (y - top_y) / (bot_y - top_y))
        gdraw.line([(90, y), (390, y)], fill=color + (255,))
    mask = Image.new("L", (W, H), 0)
    ImageDraw.Draw(mask).rounded_rectangle([96, top_y, 384, bot_y], radius=26,
                                           fill=255)
    img.paste(grad, (0, 0), mask)

    # 左亮右暗的体感条纹（高斯柔化后叠加）。
    shade = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    sdraw = ImageDraw.Draw(shade)
    sdraw.rounded_rectangle([118, top_y + 8, 154, bot_y - 10], radius=14,
                            fill=(255, 240, 210, 68))
    sdraw.rounded_rectangle([336, top_y + 8, 372, bot_y - 10], radius=14,
                            fill=(30, 16, 6, 70))
    shade = shade.filter(ImageFilter.GaussianBlur(5))
    img = Image.alpha_composite(img, shade)

    draw = ImageDraw.Draw(img)

    # 鎏金束带。
    draw.rectangle([96, 292, 384, 312], fill=GOLD + (255,))
    draw.rectangle([96, 312, 384, 320], fill=WOOD_LO + (255,))

    # 圈足。
    draw.rounded_rectangle([136, 474, 344, 510], radius=14,
                           fill=WOOD_LO + (255,))
    draw.rectangle([140, 500, 340, 506], fill=(70, 44, 20, 255))

    # 筒口沿 + 开口。
    draw.rounded_rectangle([64, 166, 416, 214], radius=22,
                           fill=WOOD_LO + (255,))
    draw.ellipse([82, 174, 398, 212], fill=OPENING + (255,))
    draw.rounded_rectangle([70, 170, 410, 182], radius=6,
                           fill=WOOD_HI + (255,))

    # 收敛到目标尺寸（Lanczos 抗锯齿）。
    small = img.resize((FINAL_W, FINAL_H), Image.LANCZOS)
    return small


def to_c_array(img: Image.Image) -> list[str]:
    pixels = list(img.getdata())
    rgb = bytearray()
    alpha = bytearray()
    for r, g, b, a in pixels:
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        rgb += value.to_bytes(2, "little")
        alpha.append(a)
    data = rgb + alpha

    lines = []
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
        lines.append(f"    {chunk},")
    return lines


def main() -> None:
    img = draw_artwork()
    rows = to_c_array(img)
    stride = FINAL_W * 2
    data_size = FINAL_W * FINAL_H * 3
    content = f"""// assets/images/fortune_img.c -- generated by
// assets/images/generate_images.py; do not edit by hand.
// 上上签签筒插画，LVGL9 RGB565A8（颜色面 + alpha 面），带 alpha 通道。
#include "lvgl.h"

static const uint8_t fortune_img_tube_data[] = {{
{chr(10).join(rows)}
}};

const lv_image_dsc_t fortune_img_tube = {{
    .header =
        {{
            .magic = LV_IMAGE_HEADER_MAGIC,
            .cf = LV_COLOR_FORMAT_RGB565A8,
            .flags = 0,
            .w = {FINAL_W},
            .h = {FINAL_H},
            .stride = {stride},
        }},
    .data_size = {data_size},
    .data = fortune_img_tube_data,
}};
"""
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({data_size} bytes image data, "
          f"{len(rows)} array lines)")


if __name__ == "__main__":
    main()
