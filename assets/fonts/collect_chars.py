#!/usr/bin/env python3
"""Generate the top-fortune font subset inventory.

Scans every C string literal in the UI-text sources (comments stripped),
collects non-ASCII codepoints, and writes assets/fonts/fortune_chars.txt.
ASCII 0x20-0x7E is implicitly covered by generate_fonts.sh and omitted.

After editing UI text or hexagram data:
    python3 assets/fonts/collect_chars.py
    ./assets/fonts/generate_fonts.sh
tests/test_fortune_text.c re-checks the result from C.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCES = [
    REPO / "main" / "fortune_text.h",
    REPO / "main" / "fortune_model.c",
    REPO / "main" / "fortune_ui.c",
    REPO / "main" / "main.c",
]
OUT = REPO / "assets" / "fonts" / "fortune_chars.txt"
OUT_48 = REPO / "assets" / "fonts" / "fortune_chars_48.txt"


def strip_comments(text: str) -> str:
    """Remove // and /* */ comments while preserving string literals."""
    out: list[str] = []
    i, n = 0, len(text)
    in_string = False
    while i < n:
        c = text[i]
        if in_string:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_string = False
            i += 1
            continue
        if c == '"':
            in_string = True
            out.append(c)
            i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


STRING_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def main() -> None:
    codepoints: set[int] = set()
    for path in SOURCES:
        if not path.exists():
            raise SystemExit(f"missing source file: {path}")
        stripped = strip_comments(path.read_text(encoding="utf-8"))
        for match in STRING_RE.finditer(stripped):
            for ch in match.group(1):
                cp = ord(ch)
                if not 0x20 <= cp <= 0x7E:
                    codepoints.add(cp)

    # 48px 大字号只渲染标题与卦名：单独生成小清单，节省 Flash。
    large: set[int] = set()
    text_header = (REPO / "main" / "fortune_text.h").read_text(
        encoding="utf-8")
    for match in STRING_RE.finditer(strip_comments(text_header)):
        large.update(ord(c) for c in match.group(1) if not 0x20 <= ord(c) <= 0x7E)
    model_src = (REPO / "main" / "fortune_model.c").read_text(
        encoding="utf-8")
    for name, _full in re.findall(
            r'FORTUNE_LEVEL_\w+,\s*"([^"]+)",\s*"([^"]+)"', model_src):
        large.update(ord(c) for c in name if not 0x20 <= ord(c) <= 0x7E)

    header = [
        "# top-fortune font subset inventory (hex codepoints, one per line).",
        "# Generated by assets/fonts/collect_chars.py; do not hand-edit.",
        "# Regenerate after editing UI text or hexagram data, then run",
        "# assets/fonts/generate_fonts.sh. ASCII 0x20-0x7E is implicit.",
        "# tests/test_fortune_text.c enforces coverage from C.",
    ]
    lines = [f"0x{cp:04X}" for cp in sorted(codepoints)]
    OUT.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    OUT_48.write_text("\n".join(header + [f"0x{cp:04X}"
                                          for cp in sorted(large)]) + "\n",
                      encoding="utf-8")
    print(f"wrote {len(lines)} codepoints to {OUT.relative_to(REPO)}")
    print(f"wrote {len(large)} codepoints to {OUT_48.relative_to(REPO)}")


if __name__ == "__main__":
    main()
