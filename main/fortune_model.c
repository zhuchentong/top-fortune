const fortune_hexagram_t *fortune_draw(uint32_t seed) {
    return &HEXAGRAMS[seed % FORTUNE_HEXAGRAM_COUNT];
}

const fortune_hexagram_t *fortune_by_number(uint8_t number) {
    if (number < 1 || number > FORTUNE_HEXAGRAM_COUNT) return NULL;
    return &HEXAGRAMS[number - 1];
}

bool fortune_line_yang(const fortune_hexagram_t *hexagram, uint8_t line) {
    if (!hexagram || line >= FORTUNE_LINE_COUNT) return false;
    return (hexagram->lines >> line) & 0x1U;
}

const char *fortune_level_label(fortune_level_t level) {
    switch (level) {
        case FORTUNE_LEVEL_SHANG_SHANG: return FORTUNE_TXT_LEVEL_SHANG_SHANG;
        case FORTUNE_LEVEL_SHANG: return FORTUNE_TXT_LEVEL_SHANG;
        case FORTUNE_LEVEL_ZHONG: return FORTUNE_TXT_LEVEL_ZHONG;
        case FORTUNE_LEVEL_XIA: return FORTUNE_TXT_LEVEL_XIA;
        default: return NULL;
    }
}

const char *fortune_level_hint(fortune_level_t level) {
    switch (level) {
        case FORTUNE_LEVEL_SHANG_SHANG: return FORTUNE_TXT_HINT_SHANG_SHANG;
        case FORTUNE_LEVEL_SHANG: return FORTUNE_TXT_HINT_SHANG;
        case FORTUNE_LEVEL_ZHONG: return FORTUNE_TXT_HINT_ZHONG;
        case FORTUNE_LEVEL_XIA: return FORTUNE_TXT_HINT_XIA;
        default: return NULL;
    }
}
